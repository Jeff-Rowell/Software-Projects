public class Tuple
{
    private final int item1;
    private final int item2;
    private final int item3;

    public Tuple(int item1, int item2, int item3)
    {
        this.item1 = item1;
        this.item2 = item2;
        this.item3 = item3;
    }

    public int getItem1()
    {
        return item1;
    }

    public int getItem2()
    {
        return item2;
    }

    public int getItem3()
    {
        return item3;
    }

}
